-- Рынки: Кудайберген (со схемой рядов) и рынки без схемы — Дордой, Дордой Моторс, Геология.
-- На рынке без схемы продавец пишет место текстом (shops.manual_place), точка магазина — точка рынка.
CREATE TABLE markets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30) NOT NULL UNIQUE,
    name_ru    VARCHAR(60) NOT NULL,
    name_kg    VARCHAR(60) NOT NULL,
    -- null — точки пока нет: «Как пройти» ищет рынок в 2GIS по названию
    lat        DOUBLE PRECISION,
    lng        DOUBLE PRECISION,
    has_scheme BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order SMALLINT    NOT NULL DEFAULT 0,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT markets_point CHECK ((lat IS NULL) = (lng IS NULL))
);

