-- ─────────────────────────── КАРТА РЫНКА ───────────────────────────
-- Координаты — в системе схемы рынка (design/market-map.json): пиксели, ось Y вниз.

-- Версия схемы: всё, что рисуется, но не выбирается (граница, проходы, входы, улицы, подписи).
-- Клиент кэширует карту и перекачивает её, только если сменился version (ETag).
CREATE TABLE map_versions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version        INT          NOT NULL UNIQUE,
    is_current     BOOLEAN      NOT NULL DEFAULT FALSE,
    boundary       JSONB        NOT NULL,   -- [[x,y],…]
    blocks         JSONB        NOT NULL,   -- невыбираемые блоки: СТО, администрация, парковка
    passages       JSONB        NOT NULL,   -- [{points, width, name:{kind,…}}] — из них граф маршрутов
    entrances      JSONB        NOT NULL,   -- [{x, y, label}]; первый — главный вход
    pois           JSONB        NOT NULL,   -- [{type: PARKING|TOILET, x, y, label}]
    streets        JSONB        NOT NULL,   -- улицы вокруг: [{name, polygon, labelX, labelY, rotate}]
    labels         JSONB        NOT NULL,   -- прочие подписи: [{text, x, y, rotate}]
    meters_per_px  NUMERIC(8,4) NOT NULL,   -- до GPS-калибровки — оценка, после — из аффинной матрицы
    geo_affine     JSONB,                   -- GPS → x,y (см. GeoCalibration); NULL — не откалибровано
    published_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_map_versions_current ON map_versions (is_current) WHERE is_current;

-- Ряд: код («14», «Ю», «Жайма 3»), геометрия — прямоугольник или многоугольник с осевой линией.
CREATE TABLE market_rows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    label       VARCHAR(40)  NOT NULL,
    type        VARCHAR(5)   NOT NULL CHECK (type IN ('ROW', 'VROW', 'STALL')),
    -- {"rect":{x,y,w,h}} или {"polygon":[[x,y]…],"axis":[[x,y]…],"halfWidth":n}
    geometry    JSONB        NOT NULL,
    sort_order  SMALLINT     NOT NULL,     -- порядок в сетке рядов (экран 10а)
    qr_token    VARCHAR(32)  NOT NULL UNIQUE,  -- табличка в начале ряда
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Контейнер: место в ряду. Координаты не храним — считаются из геометрии ряда и числа мест на стороне.
CREATE TABLE containers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_id        BIGINT       NOT NULL REFERENCES market_rows(id),
    -- горизонтальные ряды: NORTH/SOUTH, вертикальные: WEST/EAST
    side          VARCHAR(5)   NOT NULL CHECK (side IN ('NORTH', 'SOUTH', 'WEST', 'EAST')),
    number        SMALLINT     NOT NULL CHECK (number > 0),
    pos_in_row    SMALLINT     NOT NULL CHECK (pos_in_row > 0),   -- 1 — у начала осевой линии
    qr_token      VARCHAR(32)  NOT NULL UNIQUE,                    -- наклейка на контейнере
    tenant_phone  VARCHAR(16),                                     -- номер арендатора из базы рынка
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (row_id, side, number)
);
CREATE INDEX idx_containers_row ON containers (row_id, side, pos_in_row);

-- Опорные точки «GPS ↔ точка схемы» (углы рынка); по ним считается geo_affine.
CREATE TABLE geo_anchors (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lat    NUMERIC(9,6) NOT NULL,
    lon    NUMERIC(9,6) NOT NULL,
    x      NUMERIC(8,2) NOT NULL,
    y      NUMERIC(8,2) NOT NULL,
    label  VARCHAR(60)
);

