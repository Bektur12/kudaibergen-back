INSERT INTO market_rows (code, label, type, geometry, sort_order, qr_token)
SELECT code, label, type, geometry, sort_order, replace(gen_random_uuid()::text, '-', '')
FROM seed_rows;

INSERT INTO containers (row_id, side, number, pos_in_row, qr_token)
SELECT r.id, s.side, g.n, g.n, replace(gen_random_uuid()::text, '-', '')
FROM market_rows r
JOIN seed_rows sr ON sr.code = r.code
CROSS JOIN LATERAL (VALUES
    (CASE WHEN r.type = 'VROW' THEN 'WEST' ELSE 'NORTH' END),
    (CASE WHEN r.type = 'VROW' THEN 'EAST' ELSE 'SOUTH' END)) AS s(side)
CROSS JOIN LATERAL generate_series(1, sr.per_side) AS g(n);

DROP TABLE seed_rows;
