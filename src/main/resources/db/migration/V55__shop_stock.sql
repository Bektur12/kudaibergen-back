-- «Что у меня всегда есть»: продавец отмечает при регистрации и в профиле, покупатель по запросу
-- «колодки на Camry» сразу видит, у кого это обычно есть. Деталь — из справочника подсказок part_hints
-- («Колодки», «Радиатор»), тот же id приходит в запросе (part_requests.hint_id) — совпадение точное.
-- brand_id null — на все марки магазина (shop_brands), model_id null — на все модели марки.
-- source: SELF — отметил сам, ANSWERS — принял подсказку из своих ответов «Есть».
CREATE TABLE shop_stock (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id    BIGINT      NOT NULL REFERENCES shops (id) ON DELETE CASCADE,
    hint_id    BIGINT      NOT NULL REFERENCES part_hints (id) ON DELETE CASCADE,
    brand_id   BIGINT      REFERENCES brands (id) ON DELETE CASCADE,
    model_id   BIGINT      REFERENCES models (id) ON DELETE CASCADE,
    source     VARCHAR(8)  NOT NULL DEFAULT 'SELF' CHECK (source IN ('SELF', 'ANSWERS')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (model_id IS NULL OR brand_id IS NOT NULL)
);
CREATE UNIQUE INDEX shop_stock_uq ON shop_stock (shop_id, hint_id, coalesce(brand_id, 0), coalesce(model_id, 0));
-- поиск покупателя: деталь (+ марка)
CREATE INDEX shop_stock_hint_idx ON shop_stock (hint_id, brand_id);
