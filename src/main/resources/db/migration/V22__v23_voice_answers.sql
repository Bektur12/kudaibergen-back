-- Голосовые в запросе покупателя (04), в ответе продавца (14) и в отклике мастера (19): файл, длина, волна и
-- текст, распознанный сервером. Цена в ответе «Есть» и «Оригинал / Копия». «Сказали «есть», а не было» (08):
-- три покупателя за 30 дней — бокс 7 дней не получает запросов (15). Машина по фото техпаспорта (04, 10).

-- голосовое — третий вид медиа; файл видео и голосового лежит в одной колонке
ALTER TABLE media RENAME COLUMN video_key TO file_key;
ALTER TABLE media DROP CONSTRAINT media_kind_check;
ALTER TABLE media ADD CONSTRAINT media_kind_check CHECK (kind IN ('PHOTO', 'VIDEO', 'AUDIO'));
ALTER TABLE media DROP CONSTRAINT media_kind_files;
ALTER TABLE media ADD CONSTRAINT media_kind_files CHECK (
    (kind = 'PHOTO' AND key_1080 IS NOT NULL AND key_320 IS NOT NULL AND width IS NOT NULL AND height IS NOT NULL)
    OR (kind IN ('VIDEO', 'AUDIO') AND file_key IS NOT NULL AND duration_sec IS NOT NULL));
-- до 100 пиков громкости 0..1 для полоски голосового
ALTER TABLE media ADD COLUMN waveform JSONB;
-- что сказали — распознаёт сервер при загрузке; null — распознавание выключено или не удалось
ALTER TABLE media ADD COLUMN transcript VARCHAR(1000);
ALTER TABLE media DROP CONSTRAINT media_purpose_check;
ALTER TABLE media ADD CONSTRAINT media_purpose_check
    CHECK (purpose IN ('PART', 'SHOP', 'AVATAR', 'REQUEST', 'REPLY', 'MASTER', 'SERVICE', 'BRAND', 'OFFER'));

ALTER TABLE part_requests ADD COLUMN voice_media_id BIGINT REFERENCES media(id) ON DELETE SET NULL;

-- «Есть» прямо из пуша (12) — только цена: состояние у ответа необязательно, обязательна цена (проверяет сервер:
-- у старых ответов цены может не быть)
ALTER TABLE request_replies DROP CONSTRAINT request_replies_check;
ALTER TABLE request_replies ADD COLUMN voice_media_id BIGINT REFERENCES media(id) ON DELETE SET NULL;
-- «Оригинал» / «Копия» (14); null — не сказали
ALTER TABLE request_replies ADD COLUMN original BOOLEAN;
-- производитель из голоса («Оригинал KYB») и остальные чипы под ценой: «Пара», «Япония», «Контрактные» (05)
ALTER TABLE request_replies ADD COLUMN manufacturer VARCHAR(40);
ALTER TABLE request_replies ADD COLUMN tags TEXT[] NOT NULL DEFAULT '{}';

ALTER TABLE service_requests ADD COLUMN voice_media_id BIGINT REFERENCES media(id) ON DELETE SET NULL;
ALTER TABLE service_offers ADD COLUMN voice_media_id BIGINT REFERENCES media(id) ON DELETE SET NULL;

-- «сказали «есть», а не было»: одна отметка на ответ бокса
CREATE TABLE false_have_marks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT       NOT NULL REFERENCES part_requests(id) ON DELETE CASCADE,
    shop_id     BIGINT       NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    buyer_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (request_id, shop_id)
);
CREATE INDEX idx_false_have_shop ON false_have_marks (shop_id, created_at);

-- до какого момента бокс не получает запросов; с какого момента отметки считаются заново (начало паузы)
ALTER TABLE shops ADD COLUMN requests_paused_until TIMESTAMPTZ;
ALTER TABLE shops ADD COLUMN false_have_since TIMESTAMPTZ;

-- машина добавлена по фото техпаспорта — продавцы видят точную модель (10)
ALTER TABLE cars ADD COLUMN from_tech_passport BOOLEAN NOT NULL DEFAULT false;
