-- ─────────────────────────── КОММЕНТАРИИ К ВИДЕО ───────────────────────────
-- Комментарии под товаром в ленте видео («как рилсы»). Удаляет автор или продавец бокса (deleted_at),
-- скрывает админ по жалобе (hidden_by_admin).
CREATE TABLE part_comments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id          BIGINT        NOT NULL REFERENCES parts(id) ON DELETE CASCADE,
    user_id          BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text             VARCHAR(500)  NOT NULL CHECK (length(btrim(text)) >= 1),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ,
    hidden_by_admin  BOOLEAN       NOT NULL DEFAULT false,
    hidden_reason    VARCHAR(300)
);
CREATE INDEX idx_part_comments_part ON part_comments (part_id, id DESC)
    WHERE deleted_at IS NULL AND NOT hidden_by_admin;

