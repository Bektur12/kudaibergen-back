CREATE INDEX idx_master_photos_media ON master_photos (media_id);

-- ── заявка (экраны 33–36): услуга, снимок машины, что случилось, когда и где
CREATE TABLE service_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id               BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    service                VARCHAR(20)   NOT NULL REFERENCES service_types(code),
    car_id                 BIGINT        REFERENCES cars(id) ON DELETE SET NULL,
    brand_id               BIGINT        NOT NULL REFERENCES brands(id),
    model_id               BIGINT        REFERENCES models(id),
    year                   SMALLINT,
    engine_volume          NUMERIC(2, 1),
    fuel                   VARCHAR(10)   CHECK (fuel IN ('PETROL', 'DIESEL', 'LPG_PETROL', 'HYBRID', 'ELECTRIC')),
    origin                 VARCHAR(7)    NOT NULL DEFAULT 'UNKNOWN'
        CHECK (origin IN ('JAPAN', 'USA', 'EUROPE', 'KOREA', 'UAE', 'UNKNOWN')),
    description            VARCHAR(500)  NOT NULL CHECK (char_length(description) >= 10),
    when_kind              VARCHAR(8)    NOT NULL CHECK (when_kind IN ('NOW', 'TODAY', 'TOMORROW', 'AT_TIME')),
    at_time                TIMESTAMPTZ,
    where_kind             VARCHAR(12)   NOT NULL CHECK (where_kind IN ('I_COME', 'MASTER_COMES', 'PICKUP_POINT')),
    lat                    DOUBLE PRECISION NOT NULL,
    lng                    DOUBLE PRECISION NOT NULL,
    address                VARCHAR(160),
    radius_km              SMALLINT      NOT NULL DEFAULT 5 CHECK (radius_km BETWEEN 1 AND 50),
    status                 VARCHAR(7)    NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'EXPIRED', 'CLOSED')),
    duration               VARCHAR(10)   NOT NULL CHECK (duration IN ('MIN_15', 'MIN_30', 'HOUR_1', 'HOUR_3', 'END_OF_DAY')),
    sent_at                TIMESTAMPTZ   NOT NULL,
    expires_at             TIMESTAMPTZ   NOT NULL,
    extended_times         SMALLINT      NOT NULL DEFAULT 0 CHECK (extended_times BETWEEN 0 AND 3),
    recipients_count       INT           NOT NULL DEFAULT 0,
    can_help_count         INT           NOT NULL DEFAULT 0,
    closed_with_master_id  BIGINT        REFERENCES masters(id) ON DELETE SET NULL,
    closed_at              TIMESTAMPTZ,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK ((when_kind = 'AT_TIME') = (at_time IS NOT NULL))
);
CREATE INDEX idx_service_requests_buyer ON service_requests (buyer_id, created_at DESC);
CREATE INDEX idx_service_requests_expiring ON service_requests (expires_at) WHERE status = 'ACTIVE';
CREATE INDEX idx_service_requests_closed ON service_requests (closed_with_master_id, closed_at)
    WHERE closed_with_master_id IS NOT NULL;

-- до 5 фото к заявке
CREATE TABLE service_request_photos (
    request_id  BIGINT NOT NULL REFERENCES service_requests(id) ON DELETE CASCADE,
    sort        INT    NOT NULL CHECK (sort BETWEEN 0 AND 4),
    media_id    BIGINT NOT NULL REFERENCES media(id),
    PRIMARY KEY (request_id, sort)
);
CREATE INDEX idx_service_request_photos_media ON service_request_photos (media_id);

-- кому ушла заявка: лента мастера (39) и статистика заявки (37)
CREATE TABLE service_recipients (
    request_id    BIGINT      NOT NULL REFERENCES service_requests(id) ON DELETE CASCADE,
    master_id     BIGINT      NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    status        VARCHAR(9)  NOT NULL DEFAULT 'DELIVERED'
        CHECK (status IN ('DELIVERED', 'SEEN', 'CAN_HELP', 'NOT_MINE', 'EXPIRED')),
    distance_m    INT         NOT NULL,
    notified_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    seen_at       TIMESTAMPTZ,
    replied_at    TIMESTAMPTZ,
    PRIMARY KEY (request_id, master_id)
);
CREATE INDEX idx_service_recipients_feed ON service_recipients (master_id, notified_at DESC, request_id DESC);

-- отклик мастера (37, 39): один на заявку
CREATE TABLE service_offers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    BIGINT       NOT NULL REFERENCES service_requests(id) ON DELETE CASCADE,
    master_id     BIGINT       NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    answer        VARCHAR(8)   NOT NULL CHECK (answer IN ('CAN_HELP', 'NOT_MINE')),
    price_from    INT          CHECK (price_from > 0),
    available_at  TIMESTAMPTZ,
    message       VARCHAR(300),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (request_id, master_id)
);
CREATE INDEX idx_service_offers_can_help ON service_offers (request_id, id) WHERE answer = 'CAN_HELP';

-- оценка мастеру при закрытии «Договорились»
CREATE TABLE master_reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_id   BIGINT      NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    buyer_id    BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    request_id  BIGINT      UNIQUE REFERENCES service_requests(id) ON DELETE SET NULL,
    stars       SMALLINT    NOT NULL CHECK (stars BETWEEN 1 AND 5),
    tags        TEXT[]      NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_master_reviews_master ON master_reviews (master_id, created_at DESC);

-- ── чат с мастером: у чата либо магазин, либо мастер
ALTER TABLE chats ALTER COLUMN shop_id DROP NOT NULL;
ALTER TABLE chats
    ADD COLUMN master_id           BIGINT REFERENCES masters(id) ON DELETE CASCADE,
    ADD COLUMN service_request_id  BIGINT REFERENCES service_requests(id) ON DELETE SET NULL,
    ADD CONSTRAINT chats_one_provider CHECK ((shop_id IS NULL) <> (master_id IS NULL));
CREATE UNIQUE INDEX uq_chats_service_request ON chats (buyer_id, master_id, service_request_id)
    WHERE service_request_id IS NOT NULL;
CREATE UNIQUE INDEX uq_chats_master_direct ON chats (buyer_id, master_id)
    WHERE master_id IS NOT NULL AND service_request_id IS NULL;
CREATE INDEX idx_chats_master ON chats (master_id, last_message_at DESC NULLS LAST, id DESC) WHERE master_id IS NOT NULL;

