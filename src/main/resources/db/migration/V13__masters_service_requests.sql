-- ── профиль мастера / СТО (экран 38). Один на пользователя; продавец может быть и мастером
CREATE TABLE masters (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT        NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    name             VARCHAR(60)   NOT NULL,
    avatar_media_id  BIGINT        REFERENCES media(id) ON DELETE SET NULL,
    phone            VARCHAR(16),
    address          VARCHAR(160)  NOT NULL,
    lat              DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lng              DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
    radius_km        SMALLINT      NOT NULL DEFAULT 5 CHECK (radius_km BETWEEN 1 AND 30),
    is_mobile        BOOLEAN       NOT NULL DEFAULT FALSE,
    all_brands       BOOLEAN       NOT NULL DEFAULT FALSE,
    open_from        TIME          NOT NULL DEFAULT '09:00',
    open_to          TIME          NOT NULL DEFAULT '19:00',
    work_days        SMALLINT      NOT NULL DEFAULT 127 CHECK (work_days BETWEEN 1 AND 127),
    is_accepting     BOOLEAN       NOT NULL DEFAULT TRUE,
    rating           NUMERIC(2, 1) NOT NULL DEFAULT 0,
    reviews_count    INT           NOT NULL DEFAULT 0,
    status           VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('PENDING_VERIFICATION', 'ACTIVE', 'BLOCKED')),
    block_reason     VARCHAR(300),
    -- если мастер работает на рынке
    container_id     BIGINT        REFERENCES containers(id),
    public_id        VARCHAR(16)   NOT NULL UNIQUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK (open_from < open_to)
);
CREATE INDEX idx_masters_receiving ON masters (status, is_accepting);

CREATE TABLE master_services (
    master_id  BIGINT      NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    service    VARCHAR(20) NOT NULL REFERENCES service_types(code),
    PRIMARY KEY (master_id, service)
);
CREATE INDEX idx_master_services_service ON master_services (service, master_id);

CREATE TABLE master_brands (
    master_id  BIGINT NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    brand_id   BIGINT NOT NULL REFERENCES brands(id),
    PRIMARY KEY (master_id, brand_id)
);

-- пусто — любые машины
CREATE TABLE master_origins (
    master_id  BIGINT     NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    origin     VARCHAR(7) NOT NULL CHECK (origin IN ('JAPAN', 'USA', 'EUROPE', 'KOREA', 'UAE')),
    PRIMARY KEY (master_id, origin)
);

-- до 8 фото работ и места, первое — обложка
CREATE TABLE master_photos (
    master_id  BIGINT NOT NULL REFERENCES masters(id) ON DELETE CASCADE,
    sort       INT    NOT NULL CHECK (sort BETWEEN 0 AND 7),
