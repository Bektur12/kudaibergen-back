-- ─────────────────────────── ЗАКАЗ С ДОСТАВКОЙ ───────────────────────────
CREATE TABLE delivery_orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- «KDB-000123» — трек-номер в приложении и в заявке Ылдам
    number              VARCHAR(16)   UNIQUE,
    part_id             BIGINT        REFERENCES parts(id) ON DELETE SET NULL,
    shop_id             BIGINT        NOT NULL REFERENCES shops(id),
    buyer_id            BIGINT        NOT NULL REFERENCES users(id),
    chat_id             BIGINT        REFERENCES chats(id) ON DELETE SET NULL,
    -- снимок товара на момент заказа
    part_title          VARCHAR(120)  NOT NULL,
    part_price          INT           NOT NULL,
    region              VARCHAR(12)   NOT NULL,
    district            VARCHAR(12),
    address             VARCHAR(200)  NOT NULL,
    recipient_name      VARCHAR(60)   NOT NULL,
    recipient_phone     VARCHAR(20)   NOT NULL,
    -- тариф до 5 кг; NULL — цену назовёт курьер (Бишкек, пока не задана). Доплату за вес считает курьер.
    price               INT,
    days                SMALLINT      NOT NULL,
    weight_kg           NUMERIC(5, 1),
    fragile             BOOLEAN       NOT NULL DEFAULT false,
    status              VARCHAR(16)   NOT NULL DEFAULT 'NEW'
                        CHECK (status IN ('NEW', 'PACKED', 'COURIER_ORDERED', 'PICKED_UP', 'DELIVERED', 'CANCELLED')),
    created_at          TIMESTAMPTZ   NOT NULL,
    packed_at           TIMESTAMPTZ,
    courier_ordered_at  TIMESTAMPTZ,
    picked_up_at        TIMESTAMPTZ,
    delivered_at        TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ
);
CREATE INDEX idx_delivery_orders_buyer ON delivery_orders (buyer_id, id DESC);
CREATE INDEX idx_delivery_orders_shop ON delivery_orders (shop_id, id DESC);
CREATE INDEX idx_delivery_orders_status ON delivery_orders (status, id DESC);

