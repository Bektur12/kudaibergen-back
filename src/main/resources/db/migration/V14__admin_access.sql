-- ─────────────────────────── АДМИНКА: СОТРУДНИКИ, ПРАВА, ЖУРНАЛ ───────────────────────────
-- Роль сотрудника — набор прав. Проверки в коде идут только по правам, роль в коде не сравнивается:
-- новая роль (оператор, модератор…) добавляется одной миграцией — строкой в CHECK и строками прав.

CREATE TABLE admin_members (
    user_id             BIGINT       PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    admin_role          VARCHAR(12)  NOT NULL CHECK (admin_role IN ('SUPER_ADMIN', 'MARKET_ADMIN')),
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    full_name           VARCHAR(120) NOT NULL,
    -- подпись в сайдбаре: «Администратор рынка»
    title               VARCHAR(80)  NOT NULL,
    -- bcrypt; NULL — пароль не задан, войти нельзя, пока не задан по SMS-коду
    password_hash       VARCHAR(72),
    password_changed_at TIMESTAMPTZ,
    created_by          BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_login_at       TIMESTAMPTZ
);

-- Права ролей. SUPER_ADMIN в коде имеет все права всегда — строки для него не нужны и не читаются.
CREATE TABLE admin_role_permissions (
    admin_role  VARCHAR(12) NOT NULL CHECK (admin_role IN ('SUPER_ADMIN', 'MARKET_ADMIN')),
    permission  VARCHAR(32) NOT NULL,
    PRIMARY KEY (admin_role, permission)
);

