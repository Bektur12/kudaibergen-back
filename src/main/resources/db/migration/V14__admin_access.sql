-- Журнал: любое изменяющее действие админки. Строки не удаляются вместе с сотрудником.
CREATE TABLE admin_audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id     BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    action       VARCHAR(40)  NOT NULL,
    entity_type  VARCHAR(24)  NOT NULL,
    entity_id    BIGINT,
    before       JSONB,
    after        JSONB,
    comment      VARCHAR(1000),
    ip           VARCHAR(45),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_admin_audit_created ON admin_audit_log (created_at DESC, id DESC);
CREATE INDEX idx_admin_audit_entity ON admin_audit_log (entity_type, entity_id, created_at DESC);
CREATE INDEX idx_admin_audit_admin ON admin_audit_log (admin_id, created_at DESC);

-- Администрация раньше хранилась в users.admin_role — переносим и убираем колонку
INSERT INTO admin_members (user_id, admin_role, full_name, title)
SELECT id,
       CASE admin_role WHEN 'SUPERADMIN' THEN 'SUPER_ADMIN' ELSE 'MARKET_ADMIN' END,
       COALESCE(NULLIF(trim(name), ''), phone),
       CASE admin_role WHEN 'SUPERADMIN' THEN 'Суперадмин' ELSE 'Администратор рынка' END
FROM users
WHERE admin_role IS NOT NULL;

